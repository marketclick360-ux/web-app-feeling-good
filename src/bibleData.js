function seededRNG(seed) {
  let s = seed >>> 0
  return () => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0
    return s / 0x100000000
  }
}

let _sequence = null
export function getBibleSequence() {
  if (_sequence) return _sequence
  const rand = seededRNG(20250101)
  const nt = [], ot = []
  for (const book of BIBLE_BOOKS) {
    for (let ch = 1; ch <= book.chapters; ch++) {
      const entry = { slug: book.slug, chapter: ch, name: book.name, testament: book.testament, genre: book.genre, abbr: book.abbr }
      if (book.testament === 'NT') nt.push(entry)
      else ot.push(entry)
    }
  }
  for (let i = nt.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [nt[i], nt[j]] = [nt[j], nt[i]]
  }
  for (let i = ot.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [ot[i], ot[j]] = [ot[j], ot[i]]
  }
  // Interleave 2 NT : 3 OT for ~40% NT weighting early on
  const seq = []
  let ni = 0, oi = 0
  while (ni < nt.length || oi < ot.length) {
    for (let k = 0; k < 2 && ni < nt.length; k++) seq.push(nt[ni++])
    for (let k = 0; k < 3 && oi < ot.length; k++) seq.push(ot[oi++])
  }
  _sequence = seq
  return seq
}

export function jwOrgUrl(slug, chapter) {
  return `https://www.jw.org/en/library/bible/study-bible/books/${slug}/${chapter}/`
}

export function loadBibleIdx() {
  try { return Math.max(0, parseInt(localStorage.getItem('eps-bible-idx') || '0', 10)) }
  catch { return 0 }
}

export function saveBibleIdx(idx) {
  localStorage.setItem('eps-bible-idx', String(idx))
}

export function getBibleReadStats(sequence, idx) {
  const stats = {}
  for (let i = 0; i < Math.min(idx, sequence.length); i++) {
    const { slug, chapter } = sequence[i]
    if (!stats[slug]) stats[slug] = []
    if (!stats[slug].includes(chapter)) stats[slug].push(chapter)
  }
  return stats
}
